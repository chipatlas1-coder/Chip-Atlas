import { chromium } from '/opt/npm-tools/node_modules/playwright/index.mjs';
const [base, out, path, name, width] = process.argv.slice(2);
const browser = await chromium.launch({ args: ['--use-gl=angle', '--use-angle=swiftshader', '--enable-unsafe-swiftshader', '--ignore-gpu-blocklist'] });
const w = Number(width || 1366);
const page = await browser.newPage({ viewport: { width: w, height: 900 }, deviceScaleFactor: w < 500 ? 2 : 1, isMobile: w < 500, hasTouch: w < 500 });
const errors = [];
page.on('console', (m) => { if (m.type() === 'error') errors.push(m.text()); });
page.on('pageerror', (e) => errors.push(e.message));
await page.goto(base + path, { waitUntil: 'load' });
await page.waitForTimeout(800);
await page.addStyleTag({ content: '.site-header{position:static !important}' });
await page.screenshot({ path: `${out}/${name}.png`, fullPage: true });
const overflow = await page.evaluate(() => document.documentElement.scrollWidth - window.innerWidth);
console.log('errors:', errors.length ? errors.join(' | ') : 'none', '| horizontal overflow px:', overflow);
await browser.close();
