test('js / JS are symmetric ±IT/2 without rounding (ISO 286-2 prints JS7 18–30 as ±10.5)', () => {
  assert.deepEqual(holeDeviations('JS', 7, 25), { ES: 10.5, EI: -10.5 });
  assert.deepEqual(holeDeviations('JS', 9, 2), { ES: 12.5, EI: -12.5 });
  assert.deepEqual(shaftDeviations('js', 6, 25), { es: 6.5, ei: -6.5 });
});

test('fits: clearance, transition and interference at Ø25', () => {
  const a = fit('H7', 'g6', 25);
  assert.equal(a.maxClearance, 41); assert.equal(a.minClearance, 7); assert.equal(a.type, 'clearance');
  const b = fit('H7', 'k6', 25);
  assert.equal(b.maxClearance, 19); assert.equal(b.minClearance, -15); assert.equal(b.type, 'transition');
  const c = fit('H7', 's6', 25);
  assert.equal(c.maxClearance, -14); assert.equal(c.minClearance, -48); assert.equal(c.type, 'interference');
  assert.equal(fit('H7', 'G7', 25), null);
  assert.equal(parseClass('K9'), null); // not offered: published K9+ rules differ between sources
});
