function check(cls, sizes, [upper, lower]) {
  const p = parseClass(cls);
  assert.ok(p, `parse ${cls}`);
  sizes.forEach((D, i) => {
    const dev = p.kind === 'shaft' ? shaftDeviations(p.letter, p.grade, D) : holeDeviations(p.letter, p.grade, D);
    const up = p.kind === 'shaft' ? dev.es : dev.ES;
    const lo = p.kind === 'shaft' ? dev.ei : dev.EI;
    assert.equal(up, upper[i], `${cls} at ${D} mm upper`);
    assert.equal(lo, lower[i], `${cls} at ${D} mm lower`);
  });
}

